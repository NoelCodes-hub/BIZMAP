// Generate 1500+ products
function generateProducts(): Product[] {
  const products: Product[] = [];
  let id = 1;

  const allCategories = Object.keys(productTemplates);
  
  for (const category of allCategories) {
    const subcategories = productTemplates[category];
    const images = categoryImages[category] || categoryImages["Groceries"];
    
    for (const subcategoryData of subcategories) {
      for (const productTemplate of subcategoryData.products) {
        // Generate 2-4 variations of each product from different businesses
        const variations = Math.floor(Math.random() * 3) + 2;
        
        for (let v = 0; v < variations; v++) {
          const business = businesses[Math.floor(Math.random() * businesses.length)];
          const basePrice = productTemplate.priceRange[0] + 
            Math.random() * (productTemplate.priceRange[1] - productTemplate.priceRange[0]);
          const price = Math.round(basePrice * 100) / 100;
          
          const hasDiscount = Math.random() > 0.8;
          const isFeatured = Math.random() > 0.9;
          const isNew = Math.random() > 0.85;
          
          products.push({
            id: id++,
            name: productTemplate.name,
            category,
            subcategory: subcategoryData.subcategory,
            price,
            currency: "USD",
            business: business.name,
            location: business.location,
            lat: business.lat,
            lng: business.lng,
            inStock: Math.random() > 0.1,
            image: images[Math.floor(Math.random() * images.length)],
            rating: Math.round((3.5 + Math.random() * 1.5) * 10) / 10,
            reviews: Math.floor(Math.random() * 500) + 1,
            discount: hasDiscount ? Math.floor(Math.random() * 30) + 5 : undefined,
            isNew,
            isFeatured,
          });
        }
      }
    }
  }
  
  return products;
}

